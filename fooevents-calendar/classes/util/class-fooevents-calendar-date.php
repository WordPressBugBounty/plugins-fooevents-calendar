	/**
	 * Convert the php date format string to a js date format
	 *
	 * @param string $format WordPress date format.
	 * @return string
	 */
	public function format_php_to_js( $format ) {

		switch ( $format ) {
			case 'D d-m-y':
				return( 'D dd-mm-yy' );
			case 'D d-m-Y':
				return( 'D dd-mm-yy' );
			case 'l d-m-Y':
				return( 'DD dd-mm-yy' );
			case 'jS F Y':
				return( 'd MM, yy' );
			case 'F j, Y':
				return( 'MM d, yy' );
			case 'F j Y':
				return( 'MM d yy' );
			case 'j F, Y':
				return( 'd MM, yy' );
			case 'M. j, Y':
				return( 'M. d, yy' );
			case 'M. d, Y':
				return( 'M. dd, yy' );
			case 'mm/dd/yyyy':
				return( 'mm/dd/yy' );
			case 'j F Y':
				return( 'd MM yy' );
			case 'Y/m/d':
				return( 'yy/mm/dd' );
			case 'm/d/Y':
				return( 'mm/dd/yy' );
			case 'd/m/Y':
				return( 'dd/mm/yy' );
			case 'Y-m-d':
				return( 'yy-mm-dd' );
			case 'm-d-Y':
				return( 'mm-dd-yy' );
			case 'd-m-Y':
				return( 'dd-mm-yy' );
			case 'j. FY':
				return( 'd. MMyy' );
			case 'j. F Y':
				return( 'd. MM yy' );
			case 'j.m.Y':
				return( 'd.mm.yy' );
			case 'd.m.Y':
				return( 'dd.mm.yy' );
			case 'j.n.Y':
				return( 'd.m.yy' );
			case 'j. n. Y':
				return( 'd. m. yy' );
			case 'j.n. Y':
				return( 'd.m. yy' );
			case 'j \d\e F \d\e Y':
				return( "d 'de' MM 'de' yy" );
			case 'D j M Y':
				return( 'D d M yy' );
			case 'D F j':
				return( 'D MM d' );
			case 'l j F Y':
				return( 'DD d MM yy' );
			case 'l, j M Y':
				return( 'DD, d M yy' );
			case 'M d / Y':
				return( 'M dd / yy' );
			case 'M j / Y':
				return( 'M d / yy' );
			default:
				return( 'yy-mm-dd' );
		}
	}

